"""Generate the documents of the formulas from their specs (Nogat CMP-2.6).

Every Tier A formula of Hydrolog is declared once by its ``FormulaSpec``
(``hydrolog._formulas.specs()``); from the specs this script writes

* ``docs/FORMULAS.md``: the catalogue of the formulas (``formulas_markdown``);
* ``formulas/<name>.toml``: the card of each formula (``card``, Nogat
  ``schemas/formula/card-1.schema.json``, copied to ``schemas/nogat/``);
* ``src/hydrolog/_applicability.py``: the applicability ranges of the specs as plain
  data, which ``hydrolog._ranges`` serves to the catalog without importing NumPy.

``tests/contract/test_formulas.py`` compares the files with this output (DEV-10.4).

Usage::

    uv run scripts/generate_formulas.py            # write the files
    uv run scripts/generate_formulas.py --check    # fail when one is stale
"""

import argparse
import json
import math
import subprocess
import sys
import textwrap
from pathlib import Path

from hydrolog._formulas import DELEGATED, specs, tier_b
from hydrolog.nogat_formulas import (
    FormulaSpec,
    Range,
    card,
    formulas_markdown,
    to_toml,
)

ROOT = Path(__file__).resolve().parent.parent
DOCUMENT = ROOT / "docs" / "FORMULAS.md"
CARDS = ROOT / "formulas"
MODULE = ROOT / "src" / "hydrolog" / "_applicability.py"
TITLE = "Formulas of Hydrolog"

_WIDTH = 70  # text per line of a wrapped string literal (indent 12 + quotes <= 88)


def document() -> str:
    """Return the text of ``docs/FORMULAS.md``."""
    return formulas_markdown(specs(), tier_b(), delegated=DELEGATED, title=TITLE)


def cards() -> dict[str, str]:
    """Return the text of each card by its file name."""
    return {f"{spec.name}.toml": to_toml(card(spec)) for spec in specs()}


def _literal(text: str, indent: int) -> list[str]:
    """Return ``text`` as the lines of one parenthesised string literal."""
    pieces = textwrap.wrap(
        text,
        width=_WIDTH,
        drop_whitespace=False,
        break_long_words=False,
        break_on_hyphens=False,
    )
    pad = " " * indent
    return [f"{pad}{json.dumps(piece, ensure_ascii=False)}" for piece in pieces]


def _rows(spec: FormulaSpec) -> list[str]:
    """Return the ``Applicability`` rows of the inputs of a spec with a range."""
    lines: list[str] = []
    for variable in spec.variables:
        found = variable.applicability
        if not isinstance(found, Range):
            continue
        closed = found.low_inclusive and found.high_inclusive
        if not (math.isfinite(found.low) and math.isfinite(found.high) and closed):
            raise ValueError(
                f"{spec.name}.{variable.name}: the catalog serves closed, finite "
                f"applicability ranges, not {found.interval()}"
            )
        source = found.source.text() if found.source is not None else ""
        lines += [
            "    Applicability(",
            f"        method={json.dumps(spec.name)},",
            f"        parameter={json.dumps(variable.name)},",
            f"        minimum={found.low!r},",
            f"        maximum={found.high!r},",
            f"        unit={json.dumps(variable.unit, ensure_ascii=False)},",
            "        source=(",
            *_literal(source, 12),
            "        ),",
            "    ),",
        ]
    return lines


def module() -> str:
    """Return the text of ``src/hydrolog/_applicability.py``."""
    lines = [
        '"""Applicability ranges of the formulas with a spec (CMP-1.4), generated.',
        "",
        "Generated by ``scripts/generate_formulas.py`` from the ``FormulaSpec`` of",
        "each Tier A formula; do not edit. :mod:`hydrolog._ranges` serves them to",
        "the catalog, which must not import NumPy, as the specs do.",
        '"""',
        "",
        "from typing import Final, NamedTuple",
        "",
        "",
        "class Applicability(NamedTuple):",
        '    """The applicability range of one input of a formula, bounds included."""',
        "",
        "    method: str",
        "    parameter: str",
        "    minimum: float",
        "    maximum: float",
        "    unit: str",
        "    source: str",
        "",
        "",
        "APPLICABILITY: Final[tuple[Applicability, ...]] = (",
    ]
    for spec in specs():
        lines += _rows(spec)
    lines += [")", ""]
    return _formatted("\n".join(lines))


def _formatted(text: str) -> str:
    """Return ``text`` formatted by ruff with the settings of the project."""
    done = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(MODULE), "-"],
        input=text,
        capture_output=True,
        encoding="utf-8",  # ruff reads and writes UTF-8 whatever the locale's encoding
        check=True,
        cwd=ROOT,
    )
    return done.stdout


def _stale() -> list[str]:
    """Return the generated files that differ from their committed text."""
    wanted = {DOCUMENT: document(), MODULE: module()}
    wanted |= {CARDS / name: text for name, text in cards().items()}
    found = [
        path
        for path, text in wanted.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != text
    ]
    found += [path for path in sorted(CARDS.glob("*.toml")) if path not in wanted]
    return [str(path.relative_to(ROOT)) for path in found]


def main(argv: list[str] | None = None) -> int:
    """Write the files, or with ``--check`` fail when one is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="do not write")
    args = parser.parse_args(argv)
    if args.check:
        stale = _stale()
        for path in stale:
            print(f"{path} is stale: run scripts/generate_formulas.py")
        return 1 if stale else 0
    DOCUMENT.write_text(document(), encoding="utf-8", newline="\n")
    MODULE.write_text(module(), encoding="utf-8", newline="\n")
    CARDS.mkdir(exist_ok=True)
    texts = cards()
    for old in CARDS.glob("*.toml"):
        if old.name not in texts:
            old.unlink()
    for name, text in texts.items():
        (CARDS / name).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
